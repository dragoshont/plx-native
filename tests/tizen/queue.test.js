"use strict";
var assert = require("assert");
var queue = require("../../samsung/PlexTv/js/queue");
var tracks = [1, 2, 3].map(function (id) { return { type: "track", ratingKey: String(id), title: "Track " + id }; });
var test = queue.create(tracks, 1, function () { return 0; });
assert.strictEqual(test.current(), tracks[1]);
test.shuffle(true);
assert.strictEqual(test.current(), tracks[1], "Shuffle must not replace the playing track");
assert.strictEqual(new Set(test.items()).size, 3);
test.shuffle(false);
assert.strictEqual(test.position(), 1);
assert.strictEqual(test.next(), tracks[2]);
assert.strictEqual(test.next(), null);
test.repeat("all");
assert.strictEqual(test.next(), tracks[0]);
assert.strictEqual(test.previous(), tracks[2]);
test.repeat("one");
assert.strictEqual(test.next(true), tracks[2]);
assert.strictEqual(test.next(false), null, "Manual skip must not be trapped by repeat-one");
assert.throws(function () { queue.create([]); }, /1 to 200/);
assert.throws(function () { queue.create(new Array(201).fill(tracks[0])); }, /1 to 200/);
assert.throws(function () { test.repeat("silent-default"); }, /Invalid/);
assert.deepStrictEqual(tracks.map(function (track) { return track.ratingKey; }), ["1", "2", "3"]);
console.log("Tizen music queue order/shuffle/repeat/bounds: passed");
